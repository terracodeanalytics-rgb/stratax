const assert=require('node:assert/strict');
const fs=require('node:fs');
const {start}=require('./local-science-browser.cjs');

(async()=>{
 const app=await start({nativeImports:true,env:{CLOUD_COPY_FIXTURE:'1'}});
 try{
  const base='/api/projects/project';
  const before=(await app.request(base)).value;
  const setup=await app.request(base,{revision:before.revision,project:{...before.project,status:'Active',workflows:['petrophysics']},workspace:before.workspace},'PUT');
  assert.equal(setup.status,200,JSON.stringify(setup.value));
  Object.assign(app.data.project,setup.value.project,{revision:setup.value.revision});
  const {page}=await app.createPage();
  await page.locator('[data-pp-action=import]:visible').click();
  await page.locator('#wi-files').setInputFiles('.release/import-inventory-20261109/generated.zip');
  await page.locator('#wi-continue').click();
  await page.waitForFunction(()=>document.querySelector('[aria-current=step]')?.innerText.startsWith('2. Review'),null,{timeout:60000});
  const inspection=(await app.request(base+'/imports')).value.imports[0];
  const transfer=Object.values(inspection.options.perAsset).find(o=>o.archiveTransfer).archiveTransfer;
  assert.equal(transfer.excluded.length,3);
  assert.ok(transfer.excluded.some(m=>m.path.endsWith('ignored.sgy')));
  assert.ok(inspection.assets[0].size<transfer.originalSize);
  assert.ok(!inspection.assets.some(a=>['checkshots','seismic'].includes(a.family)));
  assert.ok(!inspection.datasets.some(d=>['checkshots','seismic'].includes(d.family)));
  const logs=page.locator('.ie-assets > .ie-log-group');
  assert.equal(await logs.count(),1);
  await logs.locator('summary').click();
  assert.ok(await logs.locator('[data-asset]').filter({hasText:'QA.asc'}).isVisible());
  await page.locator('#dialog [data-close]').click();
  await page.evaluate(()=>{location.hash='data';});
  await page.locator('#activate-well-import').waitFor();
  assert.deepEqual(await page.locator('[data-data-section]').evaluateAll(tabs=>tabs.map(t=>t.dataset.dataSection)),['wells','sources','history','datasets']);
  await page.locator('#activate-well-import').click();
  await page.locator('#quick-import-authority').check();
  await page.locator('#quick-import-form button[type=submit]').click();
  await page.locator('#wi-done').click();
  await page.getByRole('cell',{name:/QA Well/}).waitFor();
  await page.evaluate(()=>{location.hash='map';});
  await page.locator('.mw-unplaced-panel [data-map-command=review-locations]').click();
  const location=page.locator('#mw-bulk-locations');
  await location.waitFor();
  const row=location.locator('tr').filter({hasText:'QA Well'});
  assert.ok(Math.abs(Number(await row.locator('input[aria-label^="X or"]').inputValue())-111319.49079327357)<1e-8);
  await location.locator('[name=crs]').fill('EPSG:3857');
  await location.locator('[name=confirmed]').check();
  await location.locator('[type=submit]').click();
  await page.getByText('Converted WGS84 positions').waitFor();
  assert.match(await page.locator('#mw-location-preview').innerText(),/1\.000000, 1\.000000/);
  await location.locator('[type=submit]').click();
  await page.locator('#dialog').waitFor({state:'hidden'});
  assert.equal(await page.locator('[data-map-point]').count(),1);
  await page.evaluate(()=>{location.hash='data';});
  await page.locator('[data-data-section=sources]').click();
  await page.locator('#source-select-all').check();
  const count=await page.locator('[data-source-select]:checked').count();
  assert.equal(count,4);
  await page.locator('#source-delete-selected').click();
  await page.locator('#source-bulk-cancel').click();
  assert.equal(await page.locator('[data-source-select]').count(),count);
  const invalid=await app.request(base+'/sources/trash',{source_ids:[inspection.assets[0].id,'missing-source']});
  assert.equal(invalid.status,409);
  assert.ok(!(await app.request(base)).value.workspace.files.some(f=>f.trashed));
  await page.locator('#source-delete-all').click();
  await page.locator('#source-bulk-confirm').click();
  await page.locator('#dialog').waitFor({state:'hidden'});
  assert.equal(await page.locator('[data-source-select]').count(),0);
  await page.locator('#data-status-filter').selectOption('Trash');
  assert.equal(await page.locator('[data-source-actions]').count(),count);
  assert.equal((await app.request(base+'/imports')).value.datasets.filter(d=>d.active&&d.importId===inspection.id).length,3);
  assert.deepEqual(app.errors,[]);
  const result={passed:4,grouped:true,skipSeismic:true,skipCheckshots:true,transferBytes:inspection.assets[0].size,originalBytes:transfer.originalSize,registeredWells:true,projectedMap:true,trashed:count,activeDatasets:3,errors:app.errors};
  fs.writeFileSync('.release/import-petrophysics-20261109/browser.json',JSON.stringify(result,null,2));
  console.log(JSON.stringify(result));
 }finally{await app.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
